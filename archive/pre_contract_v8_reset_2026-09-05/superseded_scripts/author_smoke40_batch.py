def sha256_text(value: str) -> str:
    return hashlib.sha256(value.encode("utf-8")).hexdigest()


def fraction_text(value: Fraction) -> str:
    if value.denominator == 1:
        return str(value.numerator)
    return f"{value.numerator}/{value.denominator}"


def solve_age(total_age: int, darrell_parts: int, allen_parts: int, years_from_now: int) -> str:
    return fraction_text(Fraction(total_age * allen_parts, darrell_parts + allen_parts) + years_from_now)


def solve_name_letters(indras_letters: int, extra_letters: int, half_override: int | None = None) -> str:
    half = Fraction(indras_letters, 2) if half_override is None else Fraction(half_override, 1)
    return fraction_text(Fraction(indras_letters, 1) + half + extra_letters)


def solve_laps(bethany: int, trey_more: int, quinn_fewer: int) -> str:
    trey = bethany + trey_more
    shaelyn = Fraction(trey, 2)
    quinn = shaelyn - quinn_fewer
    return fraction_text(Fraction(bethany, 1) - quinn)


def solve_bananas(start: int, add_day_2: int, theft_day_2: int, add_day_3: int, first_theft_fraction: Fraction) -> str:
    after_first_theft = Fraction(start, 1) * (1 - first_theft_fraction)
    return fraction_text(after_first_theft + add_day_2 - theft_day_2 + add_day_3)


def solve_flights(second_plane_trips: int, greece_share: Fraction, france_share_of_remainder: Fraction) -> str:
    first_plane_trips = 2 * second_plane_trips
    remainder = Fraction(first_plane_trips, 1) * (1 - greece_share)
    return fraction_text(remainder * france_share_of_remainder)


def plan(*steps: str) -> str:
    return "; ".join(steps)


def solved(method: str, *, post: bool = False, accept: bool = False, structural: bool = False) -> dict[str, Any]:
    evidence: dict[str, Any] = {"method": method, "original_answer_reproduced": True}
    if post:
        evidence["post_update_answer_derived"] = True
    if accept:
        evidence["accept_signature_derived"] = True
        evidence["substitute_and_solve"] = "unique_solution"
    if structural:
        evidence["accept_signature_derived"] = True
        evidence["structural_branch_validated"] = True
    return evidence


def draft_verification() -> dict[str, Any]:
    return {
        "author_id": AUTHOR_ID,
        "verifier_id": None,
        "method": "Codex-authored draft; solver/plan branch generated by scripts/author_smoke40_batch.py; Claude review pending",
        "status": "unverified_draft",
    }


def source_verification(method: str) -> dict[str, Any]:
    return {"author_id": AUTHOR_ID, "method": method, "status": "verified"}


def scalar_signature(answer: str, detection: str) -> dict[str, Any]:
    return {"kind": "scalar", "implied_answer": answer, "detection": detection}


def branch_signature(detection: str, fires: str, does_not_fire: str, never_noticed: str) -> dict[str, Any]:
    return {
        "kind": "structural",
        "detection": detection,
        "predicate_validated_both_branches": True,
        "branch_tests": {
            "fires": fires,
            "does_not_fire": does_not_fire,
            "never_noticed": never_noticed,
        },
    }


def engagement_signature(fires: str, does_not_fire: str, never_noticed: str) -> dict[str, Any]:
    return {
        "kind": "engagement",
        "detection": fires,
        "predicate_validated_both_branches": True,
        "branch_tests": {
            "fires": fires,
            "does_not_fire": does_not_fire,
            "never_noticed": never_noticed,
        },
    }


def load_jsonl(path: Path) -> list[dict[str, Any]]:
    with path.open(encoding="utf-8") as handle:
        return [json.loads(line) for line in handle if line.strip()]


def load_trace_map() -> dict[str, dict[str, Any]]:
    traces = {}
    for record in load_jsonl(TRACE_RUN_PATH):
        traces[record["stable_source_id"]] = record
    return traces


def load_smoke10_source_map() -> dict[str, dict[str, Any]]:
    return {record["stable_source_id"]: record for record in load_jsonl(SMOKE10_SOURCE_GROUPS)}


def math_source_group(stable_source_id: str, source_map: dict[str, dict[str, Any]], trace_map: dict[str, dict[str, Any]]) -> dict[str, Any]:
    source = dict(source_map[stable_source_id])
    trace = trace_map[stable_source_id]
    if not trace.get("no_update_solved"):
        raise AssertionError(f"{stable_source_id} is not a solved no-update baseline")
    if trace.get("expected_answer") != source.get("original_answer") or trace.get("extracted_answer") != source.get("original_answer"):
        raise AssertionError(f"{stable_source_id} trace answer mismatch")
    source["source_admission_decision_id"] = ADMISSION_DECISION_ID
    source["source_admission_status"] = "provisional_development_draft"
    source["trace_run_id"] = TRACE_RUN_ID
    source["trace_id"] = trace["trace_id"]
    source["trace_run_path"] = str(TRACE_RUN_PATH.relative_to(ROOT))
    source["trace_run_status"] = "solved_no_update_baseline"
    source["expected_authored_rows"] = 4
    source["verification"] = source_verification(
        "Reused solved Smoke10 source group with Qwen3-8B no-update trace metadata checked by scripts/author_smoke40_batch.py"
    )
    return source


