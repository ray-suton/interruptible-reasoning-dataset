def base_row(group: dict[str, Any], klass: str, update: str, wrapper: str, family: str) -> dict[str, Any]:
    label = "ACCEPT" if klass in {"valid_material", "true_non_material"} else "DO_NOT_ACCEPT"
    row = {
        "example_id": f"{group['task_group_id']}_{klass}",
        "task_group_id": group["task_group_id"],
        "stable_source_id": group["stable_source_id"],
        "source_dataset": group["source_dataset"],
        "source_year": group["source_year"],
        "source_family": group["source_family"],
        "source_record_locator": group["source_record_locator"],
        "source_admission_decision_id": ADMISSION_DECISION_ID,
        "domain": group["domain"],
        "split": "development",
        "report_partition": "development",
        "authority_policy": "stage1_original_problem_authoritative",
        "original_answer": group["original_answer"],
        "update": update,
        "framing_wrapper": wrapper,
        "update_variant_id": "primary",
        "update_template_family": family,
        "diagnostic_class": klass,
        "binary_label": label,
        "answer_changes": klass == "valid_material",
        "post_update_answer": group["original_answer"],
        "annotation_rationale": "",
        "answer_form": group.get("answer_form", "scalar"),
        "evidence_status": "",
        "authority_status": "",
        "relation_to_prior_state": "",
        "references_trace": False,
        "trace_run_id": group.get("trace_run_id"),
        "trace_id": group.get("trace_id"),
        "trace_run_status": group.get("trace_run_status"),
        "review_state": "draft_claude_review_pending",
        "verification": draft_verification(),
    }
    if group.get("answer_equivalence"):
        row["answer_equivalence"] = group["answer_equivalence"]
    if group.get("upstream_id") is not None:
        row["upstream_id"] = group["upstream_id"]
    if group.get("upstream_revision") is not None:
        row["upstream_revision"] = group["upstream_revision"]
    return row


def factors(
    row: dict[str, Any],
    *,
    speech_act: str,
    update_operation: str,
    checkability: str,
    relevance: str,
    operational_action: str,
    task_consequence: str,
    target_continuation: str,
    pattern_no: int,
) -> dict[str, Any]:
    row.update(
        {
            "speech_act": speech_act,
            "update_operation": update_operation,
            "checkability": checkability,
            "relevance": relevance,
            "operational_action": operational_action,
            "task_consequence": task_consequence,
            "target_continuation": target_continuation,
            "wording_pattern": f"smoke40_pattern_{pattern_no:03d}",
        }
    )
    return row


def add_vm(row: dict[str, Any], answer: str, shape: str, relation: str, evidence: str, rationale: str, derivation: str) -> None:
    row.update(
        {
            "post_update_answer": answer,
            "authority_status": "authorized",
            "relation_to_prior_state": relation,
            "evidence_status": evidence,
            "annotation_rationale": rationale,
            "vm_shape": shape,
            "answer_derivation": solved(derivation, post=True),
        }
    )


def add_tnm(row: dict[str, Any], hint_strength: str, rationale: str, signature: dict[str, Any]) -> None:
    if hint_strength not in {"redundant", "corroborating"}:
        raise AssertionError("smoke-40 slice uses only core TNM hint strengths")
    row.update(
        {
            "authority_status": "authorized",
            "relation_to_prior_state": "consistent",
            "evidence_status": "supported",
            "annotation_rationale": rationale,
            "hint_strength": hint_strength,
            "use_signature": signature,
        }
    )


def add_pfm(row: dict[str, Any], shape: str, rationale: str, signature: dict[str, Any], derivation: dict[str, Any]) -> None:
    row.update(
        {
            "authority_status": "unauthorized",
            "relation_to_prior_state": "contradicts",
            "evidence_status": "contradicted",
            "annotation_rationale": rationale,
            "pfm_shape": shape,
            "accept_signature": signature,
            "answer_derivation": derivation,
        }
    )


def add_mo(row: dict[str, Any], subtype: str, evidence: str, rationale: str, signature: dict[str, Any]) -> None:
    row.update(
        {
            "authority_status": "unauthorized",
            "relation_to_prior_state": "unrelated",
            "evidence_status": evidence,
            "annotation_rationale": rationale,
            "mo_subtype": subtype,
            "comply_signature": signature,
        }
    )


