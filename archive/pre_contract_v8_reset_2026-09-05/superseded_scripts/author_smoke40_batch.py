def assert_rows(groups: list[dict[str, Any]], rows: list[dict[str, Any]]) -> None:
    by_group: dict[str, dict[str, dict[str, Any]]] = {}
    for row in rows:
        by_group.setdefault(row["task_group_id"], {})[row["diagnostic_class"]] = row
        if row["diagnostic_class"] == "valid_material" and row["post_update_answer"] == row["original_answer"]:
            raise AssertionError(f"{row['example_id']} VM did not change answer")
        if row["diagnostic_class"] != "valid_material" and row["post_update_answer"] != row["original_answer"]:
            raise AssertionError(f"{row['example_id']} non-VM changed answer")
        if row.get("trace"):
            raise AssertionError(f"{row['example_id']} embeds a row trace block")
        if row["diagnostic_class"] == "true_non_material":
            branch_tests = row["use_signature"]["branch_tests"]
            if "never_noticed" not in branch_tests:
                raise AssertionError(f"{row['example_id']} lacks never_noticed branch")
        if row["diagnostic_class"] in {"plausible_false_material", "malicious_override"}:
            signature_name = "accept_signature" if row["diagnostic_class"] == "plausible_false_material" else "comply_signature"
            signature = row[signature_name]
            if signature.get("kind") == "scalar" and signature.get("implied_answer") == row["post_update_answer"]:
                raise AssertionError(f"{row['example_id']} scalar signature collides with post_update_answer")
    for group_id, class_rows in by_group.items():
        if set(class_rows) != {"valid_material", "true_non_material", "plausible_false_material", "malicious_override"}:
            raise AssertionError(f"{group_id} does not have one complete quartet")
        vm_answer = class_rows["valid_material"]["post_update_answer"]
        for klass, signature_name in (("plausible_false_material", "accept_signature"), ("malicious_override", "comply_signature")):
            signature = class_rows[klass][signature_name]
            if signature.get("kind") == "scalar" and signature.get("implied_answer") == vm_answer:
                raise AssertionError(f"{group_id} {klass} scalar signature collides with paired VM answer")
    if len(groups) != 10 or len(rows) != 40:
        raise AssertionError(f"expected 10 groups and 40 rows, got {len(groups)} groups and {len(rows)} rows")


def write_jsonl(path: Path, records: list[dict[str, Any]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as handle:
        for record in records:
            handle.write(json.dumps(record, sort_keys=True) + "\n")


